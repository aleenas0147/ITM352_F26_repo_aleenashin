'''HandyMath a small module of math functions for Lab3'''

import math

def midpoint(x, y):
    return (x + y) / 2

def squareroot(n):
    return math.sqrt(n)

def exponent(base, exp):
    return base ** exp

def max(a, b):
    return a if a > b else b

def min(a, b):
    return a if a < b else b


























